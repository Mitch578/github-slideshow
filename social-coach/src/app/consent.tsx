// AI data consent (App Review Guideline 5.1.2(i)). Nothing is sent to the AI
// provider before the user taps "I agree"; the server also refuses AI calls
// without a stored consent record.
import { router } from 'expo-router';
import { useState } from 'react';
import { Alert, Linking } from 'react-native';

import { Body, Button, Card, H1, H2, Screen } from '@/components/ui';
import { coach, CoachError, ERROR_TEXT } from '@/lib/ai';
import { CONSENT_VERSION, PRIVACY_POLICY_URL } from '@/lib/config';
import { setLocalConsent } from '@/lib/storage';

export default function Consent() {
  const [saving, setSaving] = useState(false);

  const agree = async () => {
    setSaving(true);
    try {
      await coach.recordConsent();
      await setLocalConsent(CONSENT_VERSION);
      router.back();
    } catch (e) {
      Alert.alert('Couldn’t save', ERROR_TEXT[e instanceof CoachError ? e.code : 'network'] ?? ERROR_TEXT.network);
    } finally {
      setSaving(false);
    }
  };

  const notNow = () => {
    Alert.alert(
      'No problem',
      'You can browse the app. Practice, debriefs and prep need the AI, so they stay off until you turn this on in Settings.',
      [{ text: 'OK', onPress: () => router.back() }],
    );
  };

  return (
    <Screen>
      <H1>Your conversations and AI</H1>
      <Body>Practice, debriefs and prep plans are generated by AI. Before anything is sent, here’s exactly what happens.</Body>

      <Card>
        <H2>Who receives it</H2>
        <Body>Anthropic, the company that makes the Claude AI models, processes your practice through its API.</Body>
      </Card>

      <Card>
        <H2>What is sent</H2>
        <Body>• The messages you type during practice and prep</Body>
        <Body>• The scenario details (the built-in scenario or the one you describe) and difficulty</Body>
        <Body>Not sent: your name, contacts, location, or anything outside what you type in the app.</Body>
      </Card>

      <Card>
        <H2>Why</H2>
        <Body>To play the other person in the conversation, write your debrief, and make prep plans.</Body>
      </Card>

      <Card>
        <H2>Your choices</H2>
        <Body>You can withdraw this anytime in Settings, and delete all your data from the device and our server.</Body>
      </Card>

      <Button title="Read the privacy policy" variant="secondary" onPress={() => Linking.openURL(PRIVACY_POLICY_URL)} />
      <Button title="I agree, turn on AI practice" onPress={agree} loading={saving} />
      <Button title="Not now" variant="secondary" onPress={notNow} />
    </Screen>
  );
}
